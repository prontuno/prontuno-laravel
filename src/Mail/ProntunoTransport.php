<?php

declare(strict_types=1);

namespace Prontuno\Laravel\Mail;

use Prontuno\Laravel\Exceptions\ApiException;
use Prontuno\Laravel\Prontuno;
use Symfony\Component\Mailer\Envelope;
use Symfony\Component\Mailer\Exception\TransportException;
use Symfony\Component\Mailer\SentMessage;
use Symfony\Component\Mailer\Transport\AbstractTransport;
use Symfony\Component\Mime\Address;
use Symfony\Component\Mime\Email;
use Symfony\Component\Mime\Message;
use Symfony\Component\Mime\MessageConverter;
use Throwable;

/**
 * Sends Laravel mail through the Prontuno API (`MAIL_MAILER=prontuno`).
 */
final class ProntunoTransport extends AbstractTransport
{
    public const string EMAIL_ID_HEADER = 'X-Prontuno-Email-ID';

    /**
     * Headers that map to API fields or are generated by Prontuno.
     */
    private const array BYPASSED_HEADERS = [
        'from', 'to', 'cc', 'bcc', 'reply-to', 'sender', 'subject', 'content-type',
        'mime-version', 'date', 'message-id', 'return-path',
    ];

    public function __construct(private readonly Prontuno $prontuno)
    {
        parent::__construct();
    }

    protected function doSend(SentMessage $message): void
    {
        $original = $message->getOriginalMessage();

        if (! $original instanceof Message) {
            throw new TransportException('The Prontuno transport can only send MIME messages.');
        }

        $email = MessageConverter::toEmail($original);
        $envelope = $message->getEnvelope();

        try {
            // The Message-ID is unique per message, so it doubles as the idempotency key: the
            // SDK can then retry rate limits and server errors without sending twice.
            $response = $this->prontuno->emails()->send($this->payload($email, $envelope), $message->getMessageId());
        } catch (ApiException $exception) {
            throw new TransportException(
                sprintf('Request to the Prontuno API failed. Reason: %s', $exception->getMessage()),
                $exception->status(),
                $exception,
            );
        } catch (Throwable $exception) {
            throw new TransportException(
                sprintf('Request to the Prontuno API failed. Reason: %s', $exception->getMessage()),
                0,
                $exception,
            );
        }

        $ids = [];
        foreach (is_array($response['emails'] ?? null) ? $response['emails'] : [] as $accepted) {
            if (is_array($accepted) && is_string($accepted['id'] ?? null)) {
                $ids[] = $accepted['id'];
            }
        }

        if ($ids !== []) {
            $message->setMessageId($ids[0]);
            $original->getHeaders()->addTextHeader(self::EMAIL_ID_HEADER, implode(',', $ids));
        }
    }

    /**
     * @return array<string, mixed>
     */
    private function payload(Email $email, Envelope $envelope): array
    {
        // The envelope decides who receives the message, as with SMTP. Cc and Bcc are
        // limited to envelope recipients so an explicit envelope (for example one that
        // redirects mail to a review mailbox) never leaks the message to excluded
        // addresses, and every other envelope recipient is sent as To.
        $recipients = self::byMailbox($envelope->getRecipients());
        $cc = array_intersect_key(self::byMailbox($email->getCc()), $recipients);
        $bcc = array_diff_key(array_intersect_key(self::byMailbox($email->getBcc()), $recipients), $cc);
        $to = array_diff_key($recipients, $cc, $bcc);
        $to = array_replace($to, array_intersect_key(self::byMailbox($email->getTo()), $to));

        $payload = [
            'from' => ($email->getFrom()[0] ?? $envelope->getSender())->toString(),
            'to' => $this->addresses($to),
            'subject' => (string) $email->getSubject(),
        ];

        $optional = [
            'cc' => $this->addresses($cc),
            'bcc' => $this->addresses($bcc),
            'reply_to' => isset($email->getReplyTo()[0]) ? $email->getReplyTo()[0]->toString() : null,
            'text' => $this->body($email->getTextBody()),
            'html' => $this->body($email->getHtmlBody()),
            'headers' => $this->headers($email),
            'attachments' => $this->attachments($email),
        ];

        foreach ($optional as $field => $value) {
            if ($value !== null && $value !== [] && $value !== '') {
                $payload[$field] = $value;
            }
        }

        return $payload;
    }

    /**
     * Index addresses by their lower-cased mailbox, keeping the first display name.
     *
     * @param  array<Address>  $addresses
     * @return array<string, Address>
     */
    private static function byMailbox(array $addresses): array
    {
        $indexed = [];

        foreach ($addresses as $address) {
            $indexed[strtolower($address->getAddress())] ??= $address;
        }

        return $indexed;
    }

    /**
     * @param  array<Address>  $addresses
     * @return list<string>
     */
    private function addresses(array $addresses): array
    {
        return array_values(array_map(static fn (Address $address): string => $address->toString(), $addresses));
    }

    /**
     * @param  resource|string|null  $body
     */
    private function body(mixed $body): ?string
    {
        if (is_resource($body)) {
            $body = stream_get_contents($body);
        }

        return is_string($body) ? $body : null;
    }

    /**
     * @return array<string, string>
     */
    private function headers(Email $email): array
    {
        $headers = [];

        foreach ($email->getHeaders()->all() as $name => $header) {
            if (in_array(strtolower((string) $name), self::BYPASSED_HEADERS, true)) {
                continue;
            }

            $headers[$header->getName()] = $header->getBodyAsString();
        }

        return $headers;
    }

    /**
     * @return list<array<string, string>>
     */
    private function attachments(Email $email): array
    {
        $attachments = [];

        foreach ($email->getAttachments() as $attachment) {
            $headers = $attachment->getPreparedHeaders();
            $filename = $attachment->getFilename();

            if ($filename === null || trim($filename) === '') {
                $filename = 'attachment';
            }

            $item = [
                'filename' => $filename,
                'content' => base64_encode($attachment->getBody()),
                'encoding' => 'base64',
                'content_type' => $attachment->getMediaType().'/'.$attachment->getMediaSubtype(),
            ];

            if ($headers->getHeaderBody('Content-Disposition') === 'inline') {
                $item['content_id'] = $attachment->hasContentId() ? $attachment->getContentId() : $filename;
            }

            $attachments[] = $item;
        }

        return $attachments;
    }

    public function __toString(): string
    {
        return 'prontuno';
    }
}
